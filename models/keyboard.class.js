/**
 * Class representing key input state tracking for player movement and actions.
 */
class Keyboard {
  /** @type {boolean} State of the W key (e.g., jump). */
  W = false;

  /** @type {boolean} State of the A key (e.g., move left). */
  A = false;

  /** @type {boolean} State of the D key (e.g., move right). */
  D = false;

  /** @type {boolean} State of the E key (e.g., action / throw object). */
  E = false;
}
